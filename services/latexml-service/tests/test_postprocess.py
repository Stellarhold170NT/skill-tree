"""Post-processing rules that align LaTeXML output with arxiv.org/html."""

from app.engine import _post_process_html

DOC = (
    '<article class="ltx_document">'
    "<h1 class=\"ltx_title ltx_title_document\">Title</h1>"
    '<div class="ltx_authors"><span class="ltx_creator">Vineet Kumar</span></div>'
    '<div class="ltx_abstract"><p class="ltx_p">Abstract text.</p></div>'
    '<div id="p1" class="ltx_para ltx_noindent">'
    '<div id="p1.1" class="ltx_block ltx_align_bottom">'
    '<p id="p1.1.1" class="ltx_p ltx_align_center" style="width:345.0pt;">'
    "Title repeated</p>"
    '<p id="p1.1.2" class="ltx_p ltx_align_center" style="width:345.0pt;">'
    "Vineet Kumar, emails</p>"
    "</div></div>"
    '<section id="S1"><p class="ltx_p">Body.</p></section>'
    '<footer class="ltx_page_footer">Generated by LaTeXML</footer>'
    "</article>"
)


def test_acl_title_fallback_removed():
    out = _post_process_html(DOC)
    assert out.count("Vineet Kumar") == 1
    assert "Title repeated" not in out
    assert '<section id="S1">' in out
    assert 'ltx_authors_1line' in out


def test_normal_content_not_touched():
    plain = (
        '<article class="ltx_document ltx_authors_1line">'
        '<div id="p1" class="ltx_para"><p class="ltx_p">Regular paragraph.</p></div>'
        "</article>"
    )
    assert _post_process_html(plain) == plain


def test_fallback_kept_when_signature_missing():
    # Same structure but without the width/centered signature -> keep it.
    doc = DOC.replace('ltx_align_center" style="width:345.0pt;', "plain\"")
    out = _post_process_html(doc)
    assert "Vineet Kumar, emails" in out
